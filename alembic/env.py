"""
===============================================================================
PharmaSupply-ML: Alembic Environment
===============================================================================

PURPOSE
-------
Connect Alembic to the project's single database-URL resolver and support both
offline SQL generation and online migration execution.

RESPONSIBILITIES
----------------
* Add the repository root to ``sys.path`` so ``src.*`` is importable.
* Load the database URL from ``src.db_config.get_database_url()``.
* Configure Alembic for offline (``--sql``) or online execution.
* Keep ``target_metadata`` as ``None`` because migrations are authored
  explicitly rather than autogenerated from ORM metadata.

INPUTS / OUTPUTS
----------------
Inputs: ``alembic.ini`` and environment variables.
Outputs: migration SQL (offline) or schema changes (online).

ARCHITECTURE INTEGRATION
------------------------
Run manually with ``alembic upgrade head`` or from CI. The application itself
does not import Alembic; ``sql/schema.sql`` remains the bootstrap DDL for a
fresh Docker volume.
"""

from __future__ import annotations

import sys
from logging.config import fileConfig
from pathlib import Path

from sqlalchemy import engine_from_config, pool

from alembic import context

# Make the repository root importable when Alembic is launched from anywhere.
ROOT_DIR = Path(__file__).resolve().parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from src.db_config import get_database_url  # noqa: E402

# Alembic configuration object and optional logging configuration file.
config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# Single source of truth for credentials: the same resolver used by the app.
config.set_main_option("sqlalchemy.url", get_database_url())
target_metadata = None


def run_migrations_offline() -> None:
    """Run migrations without a live database connection.

    Used to inspect or version-control the generated SQL (``--sql``).
    """
    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations against a live PostgreSQL database."""
    # NullPool is appropriate for short-lived migration processes.
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
        )
        with context.begin_transaction():
            context.run_migrations()


# Alembic selects the mode based on the CLI flags.
if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
